import {test,expect} from 'bun:test';

test('Kitty input reaches CDP, local commands stay local, releases cannot quit, cleanup pops once',async()=>{
 const moduleURL=new URL('../lib/input.js',import.meta.url).href;
 const script=`
 import assert from 'node:assert/strict';
 import {EventEmitter} from 'node:events';
 import {startInputHandling,stopInputHandling} from ${JSON.stringify(moduleURL)};
 const output=[],events=[];let quits=0;
 process.stdout.write=s=>{output.push(String(s));return true;};
 process.stdin.setRawMode=()=>{};process.stdin.resume=()=>process.stdin;
 process.on('SIGINT',()=>quits++);
 const client=new EventEmitter();client.send=async(method,params)=>{events.push({method,params});return {};};
 const bar=startInputHandling(client,10,20,1,{'ctrl+e':'command','alt+l':'url_bar','ctrl+q':'quit','alt+c':'copy','ctrl+v':'paste'},()=>{});
 bar.history.file=null;
 const feed=async text=>{process.stdin.emit('data',Buffer.from(text));await Bun.sleep(15);};
 await feed('\x03');assert.equal(quits,0);
 assert.deepEqual(events.filter(e=>e.method==='Input.dispatchKeyEvent').map(e=>[e.params.key,e.params.type]),[['c','rawKeyDown'],['c','keyUp']]);
 events.length=0;
 await feed('\x1b[?0u');await feed('\x1b[?11u');
 assert.ok(output.includes('\x1b[>11u\x1b[?u'));
 await feed('\x1b[57444;9u\x1b[119;9u\x1b[119;9:2u\x1b[119;9:3u\x1b[57444;1:3u');
 const keys=()=>events.filter(e=>e.method==='Input.dispatchKeyEvent').map(e=>e.params);
 assert.deepEqual(keys().map(k=>[k.key,k.type]),[['Meta','rawKeyDown'],['w','rawKeyDown'],['w','rawKeyDown'],['w','keyUp'],['Meta','keyUp']]);
 assert.equal(keys()[1].modifiers,4);assert.equal(keys()[2].autoRepeat,true);
 events.length=0;
 await feed('\x1b[108;3u');assert.equal(bar.editing,true);assert.equal(bar.mode,'url');
 await feed('\x1b[108;1:3u');
 for(const c of 'example')await feed('\x1b['+c.charCodeAt(0)+'u\x1b['+c.charCodeAt(0)+';1:3u');
 await feed('\x1b[99;3u\x1b[99;1:3u');assert.ok(output.includes('\x1b]52;c;ZXhhbXBsZQ==\x07'));
 await feed('\x1b[118;5u');await feed('\x1b]52;c;LmNvbQ==\x07');await feed('\x1b[118;1:3u');
 assert.equal(bar.text,'example.com');assert.equal(keys().length,0);
 await feed('\x1b[27u\x1b[27;1:3u');
 await feed('\x1b[101;5u');assert.equal(bar.editing,true);assert.equal(bar.mode,'cmd');
 await feed('\x1b[101;1:3u');
 for(const c of 'hello') await feed('\x1b['+c.charCodeAt(0)+'u\x1b['+c.charCodeAt(0)+';1:3u');
 assert.equal(bar.text,'hello');assert.equal(keys().length,0);
 await feed('\x1b[99;3u\x1b[99;1:3u');
 assert.ok(output.includes('\x1b]52;c;aGVsbG8=\x07'));
 await feed('\x1b[118;5u');assert.ok(output.includes('\x1b]52;c;?\x07'));
 await feed('\x1b]52;c;'+Buffer.from('中文😀').toString('base64')+'\x07');
 await feed('\x1b[118;1:3u');
 assert.equal(bar.text,'hello中文😀');assert.equal(keys().length,0);
 await feed('\x1b[97;5u'); // Ctrl+A selects all in the local prompt
 await feed('\x1b[97;1:3u');
 for(const c of 'hello') await feed('\x1b['+c.charCodeAt(0)+'u\x1b['+c.charCodeAt(0)+';1:3u');
 assert.equal(bar.text,'hello');
 await feed('\x1b[127u\x1b[127;1:3u');assert.equal(bar.text,'hell');
 await feed('\x1b[27u\x1b[27;1:3u');assert.equal(bar.editing,false);
 await feed('\x1b[97;2u\x1b[97;2:2u\x1b[97;1:3u');
 assert.equal(keys().filter(k=>k.type==='char').map(k=>k.text).join(''),'AA');
 events.length=0;
 await feed('\x1b[99;5u\x1b[99;1:3u');assert.equal(quits,0);
 assert.deepEqual(keys().map(k=>[k.key,k.type,k.modifiers]),[['c','rawKeyDown',2],['c','keyUp',0]]);
 events.length=0;
 await feed('\x03');assert.equal(quits,0);assert.equal(keys()[0].key,'c');
 await feed('\x1b[99;1:3u');
 events.length=0;
 await feed('\x1b[101;5u\x1b[101;1:3u');assert.equal(bar.editing,true);
 bar.insertText('copy me');
 await feed('\x1b[99;5u\x1b[99;1:3u');assert.equal(bar.editing,true);assert.equal(quits,0);
 assert.ok(output.includes('\x1b]52;c;'+Buffer.from('copy me').toString('base64')+'\x07'));
 bar.moveCursor(0);bar.moveCursor(4,true);
 await feed('\x03');assert.equal(bar.editing,true);assert.equal(bar.selectedText,'copy');
 assert.ok(output.includes('\x1b]52;c;'+Buffer.from('copy').toString('base64')+'\x07'));
 await feed('\x1b[99;1:3u');
 await feed('\x1b[27u\x1b[27;1:3u');assert.equal(bar.editing,false);
 // A repeat of a widget's cancelling key must not become a page key.
 await feed('\x1b[108;3u\x1b[108;1:3u');assert.equal(bar.mode,'url');
 await feed('\x1b[27u\x1b[27;1:2u\x1b[27;1:3u');assert.equal(bar.editing,false);
 assert.equal(keys().length,0);
 await feed('\x1b[113;5:3u');assert.equal(quits,0);
 await feed('\x1b[113;5u');assert.equal(quits,1);
 stopInputHandling();stopInputHandling();assert.equal(output.filter(s=>s==='\x1b[<u').length,1);
 assert.equal(keys().length,0);
 process.exit(0);
 `;
 const child=Bun.spawn([process.execPath,'-e',script],{stdout:'pipe',stderr:'pipe'});
 const errors=new Response(child.stderr).text();
 const status=await child.exited;const stderr=await errors;
 if(status)console.error(stderr);
 expect(status).toBe(0);expect(stderr).toBe('');
},10000);
